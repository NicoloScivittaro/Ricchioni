import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { launch, HOST_URL } from './lib.mjs';
const browser=await launch();
try {
  const p=await browser.newPage(),errors=[];
  p.on('pageerror',e=>errors.push(String(e)));
  await p.goto(`${HOST_URL}?fighter=1&goblin=new`,{waitUntil:'load'});
  await p.waitForFunction(()=>window.__fighterLab?.game(),{timeout:60000});
  await p.evaluate(()=>window.__fighterLab.restart(2,'all-goblin'));
  await p.waitForFunction(()=>[...window.__fighterLab.game().entities.values()].every(e=>e.goblinDebug()?.state==='ready'),{timeout:60000});
  await p.waitForFunction(()=>window.__fighterLab.game().phase==='playing',{timeout:30000});
  const result=await p.evaluate(async()=>{
    const g=window.__fighterLab.game(),f=g.sim.fighters[0],ent=g.entities.get(f.id);
    const {NO_INPUT}=await import('/src/minigames/cornicione/fighterTypes.ts');
    const {PHYS,STAGE,WALL,KO}=await import('/src/minigames/cornicione/fighterData.ts');
    g.setPaused(true);for(const x of g.sim.fighters)g.setBot(x.id,false);
    const setup=(extra={})=>{Object.assign(f,{x:0,y:0,vx:0,vy:0,grounded:true,support:0,hitstun:0,hitFlash:0,invuln:0,intang:0,attack:null,dodge:null,hover:0,percent:0,landLag:0,dodgeCd:0,jumps:2,airDodgeUsed:false,frozenT:0,lives:3,dead:false,inGame:true,wallSide:0,wallCharges:WALL.charges,jumpBuf:0,dodgeBuf:0,attackBuf:0,...extra});f.ab.burstT=f.ab.returnT=f.ab.followT=f.ab.vanishT=0;};
    const step=(input={},dt=.016)=>{g.sim.step(dt,new Map([[f.id,{...NO_INPUT,...input}]]));const events=g.sim.drainEvents();for(const e of events)g.handle(e);g.updateVisuals(dt,performance.now());g.scene.render();return events.map(e=>e.t);};
    setup();step({mx:1,dodgePressed:true});
    const dodge={active:!!f.dodge,clip:ent.goblinDebug().animator.name};
    setup({y:3,grounded:false,support:-1});step({mx:1,dodgePressed:true});
    const dash={air:!!f.dodge?.air,clip:ent.goblinDebug().animator.name};
    setup({x:STAGE.mainX+PHYS.halfW+.02,y:-3,vx:-2,vy:-2,grounded:false,support:-1});
    const wallEvents=[];for(let i=0;i<15&&f.wallSide===0;i++)wallEvents.push(...step({mx:-1}));
    const wall={side:f.wallSide,charges:f.wallCharges,events:wallEvents,clip:ent.goblinDebug().animator.name};
    const jumpEvents=step({mx:1,jumpPressed:true,jumpHeld:true});
    const wallJump={events:jumpEvents,vx:f.vx,vy:f.vy,clip:ent.goblinDebug().animator.name};
    setup({x:STAGE.mainX+3,y:-3,vy:-5,grounded:false,support:-1});step();
    const fall={clip:ent.goblinDebug().animator.name,y:ent.root.position.y,hips:ent.goblinDebug().hipsNow,rest:ent.goblinDebug().restHips};
    f.y=KO.minY-1;const koEvents=step();
    const ringout={events:koEvents,dead:f.dead,lives:f.lives,visible:ent.root.isEnabled()};
    let respawnEvents=[];for(let i=0;i<130&&f.dead;i++)respawnEvents.push(...step());
    const respawn={events:respawnEvents,dead:f.dead,visible:ent.root.isEnabled(),y:f.y,clip:ent.goblinDebug().animator.name};
    setup({y:.08,vy:-2,grounded:false,support:-1});step();step();
    const landing={grounded:f.grounded,clip:ent.goblinDebug().animator.name};
    return {dodge,dash,wall,wallJump,fall,ringout,respawn,landing};
  });
  assert.equal(result.dodge.active,true);assert.equal(result.dodge.clip,'goblin.dodge');
  assert.equal(result.dash.air,true);assert.equal(result.dash.clip,'goblin.dash');
  assert.ok(result.wall.events.includes('wall'));assert.notEqual(result.wall.side,0);
  assert.ok(result.wallJump.events.includes('wallJump'));assert.ok(result.wallJump.vy>8);
  assert.equal(result.fall.clip,'goblin.fall');assert.ok(Math.abs(result.fall.hips[1]-result.fall.rest[1])<1e-4);
  assert.ok(result.ringout.events.includes('ko'));assert.equal(result.ringout.dead,true);assert.equal(result.ringout.visible,false);
  assert.ok(result.respawn.events.includes('respawn'));assert.equal(result.respawn.dead,false);assert.equal(result.respawn.visible,true);
  assert.equal(result.landing.grounded,true);assert.equal(result.landing.clip,'goblin.idle');
  assert.equal(errors.length,0,errors.join(';'));
  writeFileSync('docs/agent-work/goblin-animation-phase/cornicione-physics.json',JSON.stringify({result,errors},null,2));
  console.log('Cornicione Tripo: ground dodge, air dash, wall cling/jump, fall, real ring-out, hidden body, respawn and landing: PASS');
} finally {await browser.close();}
