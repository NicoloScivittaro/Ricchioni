import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {Server} from 'socket.io';
import {io,type Socket} from 'socket.io-client';
import {writeFileSync} from 'node:fs';
import {RoomManager} from '../server/RoomManager';
import type {GameSession} from '../server/GameSession';
import {EVT} from '../shared/protocol';
import {FLOW_TIMING,type RoomState} from '../shared/types';
const http=createServer(),server=new Server(http),manager=new RoomManager(server),clients:Socket[]=[],checks:string[]=[];
server.on('connection',s=>manager.handleConnection(s));
const wait=async(fn:()=>unknown,label:string,ms=6000)=>{const t=Date.now();while(!fn()){if(Date.now()-t>ms)throw Error('Timeout '+label);await new Promise(r=>setTimeout(r,20));}};
const ack=(s:Socket,event:string,p:unknown)=>new Promise<any>((resolve,reject)=>s.timeout(2500).emit(event,p,(e:Error|null,r:unknown)=>e?reject(e):resolve(r)));
const ok=(b:unknown,label:string)=>{assert.ok(b,label);checks.push(label);};
let state:RoomState|undefined;const phases:string[]=[],picks:any[]=[];
const connect=async()=>{const s=io(`http://127.0.0.1:${(http.address() as {port:number}).port}`,{transports:['websocket'],forceNew:true});clients.push(s);await new Promise<void>(r=>s.once('connect',()=>r()));return s;};
const timing=FLOW_TIMING as unknown as {mapVoteMs:number},oldTiming=timing.mapVoteMs;timing.mapVoteMs=4000;
try{
  await new Promise<void>(r=>http.listen(0,'127.0.0.1',()=>r()));
  const host=await connect();host.on(EVT.roomState,(s:RoomState)=>{state=s;phases.push(s.phase);});host.on(EVT.minigameSelected,p=>picks.push(p));
  const created=await ack(host,EVT.hostCreate,{playerCount:2,targetScore:60});
  const a=await connect(),b=await connect(),stranger=await connect();
  const ja=await ack(a,EVT.playerJoin,{roomCode:created.roomCode,displayName:'Ada'}),jb=await ack(b,EVT.playerJoin,{roomCode:created.roomCode,displayName:'Bruno'});
  a.emit(EVT.playerSelectCharacter,{characterId:'goblin'});b.emit(EVT.playerSelectCharacter,{characterId:'ciro'});a.emit(EVT.playerReady,{ready:true});b.emit(EVT.playerReady,{ready:true});
  await wait(()=>state?.players.every(p=>p.ready&&p.characterId),'ready');
  host.emit(EVT.hostSelectMinigame,{minigameId:'backrooms'});host.emit(EVT.hostStart);await wait(()=>state?.phase==='MINIGAME_ROULETTE','roulette');host.emit(EVT.hostSkip);await wait(()=>state?.phase==='MINIGAME_MAP_VOTE','vote');
  const roundId=state!.roundId!,deadline=state!.mapVote!.endsAt,payload={roundId,mapId:'lobby'};
  ok(!(await ack(stranger,EVT.mapVote,payload)).ok,'unjoined phone rejected');
  ok(!(await ack(stranger,EVT.hostMapVote,{...payload,playerId:ja.playerId})).ok,'phone cannot use host relay');
  ok(!(await ack(a,EVT.mapVote,{roundId:roundId-1,mapId:'lobby'})).ok,'stale round rejected over socket');
  ok(!(await ack(a,EVT.mapVote,{roundId,mapId:'arcobaleno'})).ok,'map from another game rejected');
  ok((await ack(a,EVT.mapVote,{...payload,playerId:jb.playerId})).ok,'phone ballot accepted using socket identity');
  await wait(()=>state?.mapVote?.votes[ja.playerId]==='lobby','vote reflected');
  ok(!state!.mapVote!.votes[jb.playerId],'payload cannot impersonate another player');
  await ack(a,EVT.mapVote,payload);ok(Object.keys(state!.mapVote!.votes).length===1,'repeat does not double count');
  ok(!(await ack(host,EVT.hostMapVote,{...payload,playerId:ja.playerId})).ok,'unpaired host relay rejected');
  host.emit(EVT.hostGamepads,{pads:{[ja.playerId]:'Xbox'}});await wait(()=>state?.players[0].pad==='Xbox','pad paired');
  ok((await ack(host,EVT.hostMapVote,{roundId,mapId:'garage',playerId:ja.playerId})).ok,'associated host pad ballot accepted');
  const a2=await connect();const reconnect=await ack(a2,EVT.playerJoin,{reconnectToken:ja.reconnectToken,roomCode:'',displayName:''});
  ok(reconnect.playerId===ja.playerId,'reconnect preserves voter identity');
  ok(!(await ack(a,EVT.mapVote,payload)).ok,'replaced socket cannot vote');
  ok((await ack(a2,EVT.mapVote,{roundId,mapId:'tunnels'})).ok,'reconnected phone can replace ballot');
  ok((await ack(b,EVT.mapVote,{roundId,mapId:'tunnels'})).ok,'second player votes');
  const host2=await connect();host2.on(EVT.roomState,(s:RoomState)=>{state=s;phases.push(s.phase);});host2.on(EVT.minigameSelected,p=>picks.push(p));
  await ack(host2,EVT.hostCreate,{hostToken:created.hostToken});await wait(()=>state?.mapVote?.votes[jb.playerId]==='tunnels','reconnected host snapshot');
  ok(state!.mapVote!.endsAt===deadline,'host reconnect does not reset deadline');
  ok(!(await ack(host,EVT.hostMapVote,{roundId,mapId:'lobby',playerId:ja.playerId})).ok,'replaced host socket cannot cast');
  host2.emit(EVT.hostSkip);await new Promise(r=>setTimeout(r,80));ok(state!.phase==='MINIGAME_MAP_VOTE'&&!phases.includes('MINIGAME_PLAYING'),'no early game or animation skip bypass');
  await wait(()=>state?.phase==='MINIGAME_INTRO','real deadline -> intro');
  ok(state!.currentMinigame!.mapId==='tunnels'&&picks.at(-1).mapId==='tunnels','deadline delivers selected map in snapshot and payload');
  ok(!(await ack(a2,EVT.mapVote,{roundId,mapId:'garage'})).ok,'late socket ballot rejected');
  host2.emit(EVT.hostSkip);await wait(()=>state?.phase==='MINIGAME_PLAYING','playing');
  host2.emit(EVT.hostRestartMatch);await wait(()=>state?.phase==='LOBBY','restart');ok(!state!.mapVote&&!state!.currentMinigame,'restart removes ballot');
  console.log(`PASS map voting network: ${checks.length} authenticated socket and deadline checks.`);
}finally{
  timing.mapVoteMs=oldTiming;
  for(const room of (manager as unknown as {rooms:Map<string,GameSession>}).rooms.values())room.resetToLobby();
  clients.forEach(s=>s.disconnect());await new Promise<void>(r=>server.close(()=>r()));
  writeFileSync('docs/agent-work/map-voting/network-checks.json',JSON.stringify({checks,phases,picks,passed:checks.length},null,2));
}
