"""Original eerie music-box and wooden mechanism cues; no sampled CoD audio."""
from pathlib import Path
import json, wave
import numpy as np

root = Path(__file__).resolve().parents[2]
dest = root / 'public/assets/orda/audio'
dest.mkdir(parents=True, exist_ok=True)
rate = 44100
rng = np.random.default_rng(950)
def pluck(target, start, hz, duration=.34, gain=.16):
    t = np.arange(int(duration * rate)) / rate
    bell = (np.sin(2*np.pi*hz*t) * np.exp(-t*9)
            + .32*np.sin(2*np.pi*hz*2.003*t)*np.exp(-t*15)
            + .12*np.sin(2*np.pi*hz*3.97*t)*np.exp(-t*22))
    bell *= np.minimum(1, t/.003) * gain
    i = int(start * rate)
    n = min(len(bell), len(target)-i)
    target[i:i+n] += bell[:n]
def clack(target, start, gain=.12, duration=.08):
    t = np.arange(int(duration*rate))/rate
    noise = rng.normal(0, 1, len(t))
    noise = np.convolve(noise, np.ones(6)/6, mode='same')
    clip = (noise*.7+np.sin(2*np.pi*135*t)*.6)*np.exp(-t*45)*gain
    i = int(start*rate)
    n = min(len(clip), len(target)-i)
    target[i:i+n] += clip[:n]
roll = np.zeros(int(2.5*rate))
clack(roll, .0, .35, .18)
notes = [1046.5, 1244.5, 1568., 987.8, 1174.7, 1396.9, 1046.5, 1244.5, 1568., 987.8, 1174.7, 1396.9, 1244.5, 1046.5]
times = [.16, .42, .66, .88, 1.08, 1.26, 1.42, 1.57, 1.71, 1.84, 1.96, 2.07, 2.17, 2.26]
for at, hz in zip(times, notes):
    pluck(roll, at, hz, .24, .14)
    clack(roll, at-.025, .065)
ready = np.zeros(int(1.15*rate))
for at, hz in [(0, 523.25), (.065, 783.99), (.13, 1046.5), (.2, 1244.5)]:
    pluck(ready, at, hz, .8, .17)
close = np.zeros(int(.96*rate))
clack(close, .08, .075, .2)
clack(close, .32, .045, .16)
# Lid reaches the rim at .65 seconds: align the wooden impact to that instant.
clack(close, .65, .5, .24)
t = np.arange(len(close)-int(.65*rate))/rate
close[int(.65*rate):] += np.sin(2*np.pi*(85*t-35*t*t))*np.exp(-t*18)*.3
report = []
for name, clip in [('roll', roll), ('ready', ready), ('close', close)]:
    # A quiet single voice remains comfortably below the existing mixer limiter.
    clip = np.clip(clip, -.8, .8)
    with wave.open(str(dest/(name+'.wav')), 'wb') as wav:
        wav.setnchannels(1); wav.setsampwidth(2); wav.setframerate(rate)
        wav.writeframes((clip*32767).astype('<i2').tobytes())
    report.append({'name': name, 'seconds': len(clip)/rate, 'peak': float(np.max(np.abs(clip))), 'rms': float(np.sqrt(np.mean(clip**2)))})
(root/'docs/agent-work/orda-box-polish/audio.json').write_text(json.dumps(report, indent=2), encoding='utf8')
(dest/'CREDITS.md').write_text('Original procedural cues generated by tools/orda/box-sound.py: music-box arpeggio, mechanism clicks, reward chime and wooden closing impact. No Call of Duty recordings or sampled soundtrack.\n', encoding='utf8')
print(json.dumps(report))
